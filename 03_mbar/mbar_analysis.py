def load_metadata(metadata_path: Path):
    """
    Read:
        window_index, center, k_bias, n_samples, acceptance_ratio
    """
    rows = []

    with open(metadata_path, "r", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)

        for row in reader:
            rows.append(
                {
                    "index": int(row["window_index"]),
                    "center": float(row["center"]),
                    "k_bias": float(row["k_bias"]),
                    "n_samples": int(row["n_samples"]),
                    "acceptance": float(row["acceptance_ratio"]),
                }
            )

    rows.sort(key=lambda item: item["index"])

    if not rows:
        raise RuntimeError(
            f"No umbrella states found in {metadata_path}"
        )

    return rows


def load_window_samples(
    input_directory: Path,
    metadata,
    max_samples_per_window: int = 0,
):
    """
    Load every saved umbrella window.

    max_samples_per_window = 0 means use every stored sample.
    A positive value evenly thins each stored trajectory to at most that size.
    """
    windows = []

    for state in metadata:
        sample_path = input_directory / (
            f"window_{state['index']:02d}_samples.csv"
        )

        samples = np.loadtxt(
            sample_path,
            delimiter=",",
            skiprows=1,
        )

        samples = np.atleast_1d(samples).astype(float)

        if (
            max_samples_per_window > 0
            and len(samples) > max_samples_per_window
        ):
            indices = np.linspace(
                0,
                len(samples) - 1,
                max_samples_per_window,
                dtype=int,
            )
            samples = samples[indices]

        windows.append(
            {
                **state,
                "samples": samples,
                "n_used": len(samples),
            }
        )

    return windows


def pool_samples(windows):
    """
    Concatenate all samples and remember their source state.
    """
    all_samples = []
    origin_state = []

    for i, window in enumerate(windows):
        samples = window["samples"]

        all_samples.append(samples)

        origin_state.append(
            np.full(
                len(samples),
                i,
                dtype=int,
            )
        )

    return (
        np.concatenate(all_samples),
        np.concatenate(origin_state),
    )


# ---------------------------------------------------------------------------
# Build u_kn: reduced potential of every pooled sample in every sampled state.
# ---------------------------------------------------------------------------

def build_reduced_potential_matrix(
    pooled_samples: np.ndarray,
    windows,
):
    """
    u_kn[k, n] = u_k(x_n)

    Shape:
        K sampled states x N pooled samples.
    """
    K = len(windows)
    N = len(pooled_samples)

    u_kn = np.empty((K, N), dtype=float)

    for k, window in enumerate(windows):
        u_kn[k, :] = reduced_potential(
            pooled_samples,
            center=window["center"],
            k_bias=window["k_bias"],
        )

    return u_kn


# ---------------------------------------------------------------------------
# MBAR Eq. (11).
# ---------------------------------------------------------------------------

def mbar_log_denominator(
    f_k: np.ndarray,
    u_kn: np.ndarray,
    N_k: np.ndarray,
):
    """
    For each pooled configuration x_n compute

        log d_n =
        log sum_k N_k exp(f_k - u_k(x_n))
    """
    log_N_k = np.log(N_k)

    terms = (
        log_N_k[:, None]
        + f_k[:, None]
        - u_kn
    )

    return logsumexp(
        terms,
        axis=0,
    )


def solve_mbar(
    u_kn: np.ndarray,
    N_k: np.ndarray,
    initial_f: np.ndarray | None = None,
    tolerance: float = 1.0e-10,
    max_iterations: int = 20_000,
):
    """
    Solve Paper 5 Eq. (11) by self-consistent iteration.

    Because all f_i are determined only up to an additive constant,
    f_0 is shifted to zero after every iteration.
    """
    K, _ = u_kn.shape

    if np.any(N_k <= 0):
        raise ValueError(
            "This solver expects positive N_k for all sampled states."
        )

    if initial_f is None:
        f_k = np.zeros(K, dtype=float)
    else:
        f_k = np.asarray(
            initial_f,
            dtype=float,
        ).copy()

        f_k -= f_k[0]

    for iteration in range(max_iterations):
        log_denom_n = mbar_log_denominator(
            f_k,
            u_kn,
            N_k,
        )

        new_f = np.empty(K, dtype=float)

        for i in range(K):
            log_c_i = logsumexp(
                -u_kn[i, :]
                - log_denom_n
            )

            new_f[i] = -log_c_i

        # Gauge fixing: only differences matter.
        new_f -= new_f[0]

        maximum_change = np.max(
            np.abs(new_f - f_k)
        )

        f_k = new_f

        if maximum_change < tolerance:
            return (
                f_k,
                iteration + 1,
                maximum_change,
            )

    return (
        f_k,
        max_iterations,
        maximum_change,
    )


# ---------------------------------------------------------------------------
# MBAR weights for sampled states and for an UNSAMPLED unbiased target state.
# ---------------------------------------------------------------------------

def sampled_state_weights(
    f_k: np.ndarray,
    u_kn: np.ndarray,
    N_k: np.ndarray,
):
    """
    Paper 5 Eq. (9):

        W_ni =
        exp(f_i - u_i(x_n))
        /
        sum_k N_k exp(f_k - u_k(x_n))

    Returned shape is N samples x K states.
    """
    log_denom_n = mbar_log_denominator(
        f_k,
        u_kn,
        N_k,
    )

    log_weights = (
        f_k[:, None]
        - u_kn
        - log_denom_n[None, :]
    )

    return np.exp(log_weights).T


def unsampled_target_weights(
    target_u_n: np.ndarray,
    f_k: np.ndarray,
    u_kn: np.ndarray,
    N_k: np.ndarray,
):
    """
    Estimate the normalization constant and normalized weights for a state
    from which NO samples were directly collected.

    This uses the same MBAR denominator as the sampled states:

        c_target =
        sum_n exp(-u_target(x_n)) / d_n

        f_target = -ln(c_target)

        w_n,target =
        exp(f_target - u_target(x_n)) / d_n
    """
    log_denom_n = mbar_log_denominator(
        f_k,
        u_kn,
        N_k,
    )

    log_c_target = logsumexp(
        -target_u_n
        - log_denom_n
    )

    f_target = -log_c_target

    log_weights = (
        f_target
        - target_u_n
        - log_denom_n
    )

    weights = np.exp(log_weights)

    # Numerical cleanup.
    weights /= np.sum(weights)

    return (
        weights,
        f_target,
    )


# ---------------------------------------------------------------------------
# Equilibrium observables and PMF.
# ---------------------------------------------------------------------------

def weighted_expectation(
    observable_values: np.ndarray,
    weights: np.ndarray,
):
    """<A> = sum_n w_n A(x_n)."""
    return float(
        np.sum(
            weights
            * observable_values
        )
    )


def weighted_probability_mass(
    samples: np.ndarray,
    weights: np.ndarray,
    edges: np.ndarray,
):
    """
    Sum MBAR target weights inside each coordinate bin.
    """
    bin_indices = np.digitize(
        samples,
        edges,
    ) - 1

    probability = np.zeros(
        len(edges) - 1,
        dtype=float,
    )

    valid = (
        (bin_indices >= 0)
        & (bin_indices < len(probability))
    )

    np.add.at(
        probability,
        bin_indices[valid],
        weights[valid],
    )

    total = probability.sum()

    if total > 0.0:
        probability /= total

    return probability


def probability_to_pmf(
    probability: np.ndarray,
):
    """
    G(x) = -kBT ln P(x) + C
    """
    pmf = np.full(
        len(probability),
        np.nan,
        dtype=float,
    )

    positive = probability > 0.0

    pmf[positive] = (
        -KB
        * T
        * np.log(
            probability[positive]
        )
    )

    pmf[positive] -= np.nanmin(
        pmf[positive]
    )

    return pmf


def exact_pmf(
    bin_centers: np.ndarray,
):
    values = physical_potential(
        bin_centers
    )

    return values - np.min(values)


def pmf_rmse(
    reconstructed: np.ndarray,
    exact: np.ndarray,
):
    valid = (
        np.isfinite(reconstructed)
        & np.isfinite(exact)
    )

    if not np.any(valid):
        return np.nan

    return float(
        np.sqrt(
            np.mean(
                (
                    reconstructed[valid]
                    - exact[valid]
                )
                ** 2
            )
        )
    )


# ---------------------------------------------------------------------------
# Overlap diagnostic.
# ---------------------------------------------------------------------------

def mbar_overlap_matrix(
    W_nk: np.ndarray,
    origin_state: np.ndarray,
    N_k: np.ndarray,
):
    """
    Construct a row-stochastic diagnostic matrix.

    For a sample n, N_j * W_nj can be interpreted as the fractional
    responsibility of sampled state j in the MBAR denominator.

    For each source state i, average those responsibilities over samples
    that actually came from i.

    Strong diagonal-only structure means poor inter-state overlap.
    Significant neighboring off-diagonal values indicate useful overlap.
    """
    responsibilities = (
        W_nk
        * N_k[None, :]
    )

    K = len(N_k)
    overlap = np.zeros((K, K))

    for i in range(K):
        mask = origin_state == i

        if np.any(mask):
            overlap[i, :] = np.mean(
                responsibilities[mask, :],
                axis=0,
            )

    return overlap


# ---------------------------------------------------------------------------
# Optional stratified bootstrap.
# ---------------------------------------------------------------------------

def stratified_bootstrap_pmf(
    windows,
    edges,
    n_bootstrap: int,
    seed: int,
    original_f: np.ndarray,
):
    """
    Resample WITH replacement inside each original umbrella window,
    re-solve MBAR, and rebuild the unbiased PMF.

    This is a pedagogical bootstrap uncertainty estimate, not the paper's
    asymptotic covariance estimator.
    """
    if n_bootstrap <= 0:
        return None

    rng = np.random.default_rng(seed)

    pmfs = []

    for replicate in range(n_bootstrap):
        bootstrap_windows = []

        for window in windows:
            samples = window["samples"]

            indices = rng.integers(
                0,
                len(samples),
                size=len(samples),
            )

            bootstrap_windows.append(
                {
                    **window,
                    "samples": samples[indices],
                    "n_used": len(samples),
                }
            )

        pooled, _ = pool_samples(
            bootstrap_windows
        )

        N_k = np.array(
            [
                window["n_used"]
                for window in bootstrap_windows
            ],
            dtype=float,
        )

        u_kn = build_reduced_potential_matrix(
            pooled,
            bootstrap_windows,
        )

        f_k, _, _ = solve_mbar(
            u_kn,
            N_k,
            initial_f=original_f,
            tolerance=1.0e-8,
            max_iterations=10_000,
        )

        target_u = target_reduced_potential(
            pooled
        )

        weights, _ = unsampled_target_weights(
            target_u,
            f_k,
            u_kn,
            N_k,
        )

        probability = weighted_probability_mass(
            pooled,
            weights,
            edges,
        )

        pmfs.append(
            probability_to_pmf(
                probability
            )
        )

        print(
            f"  bootstrap {replicate + 1}/{n_bootstrap}"
        )

    pmfs = np.asarray(pmfs)

    with np.errstate(
        invalid="ignore",
        divide="ignore",
    ):
        uncertainty = np.nanstd(
            pmfs,
            axis=0,
            ddof=1,
        )

    return uncertainty


