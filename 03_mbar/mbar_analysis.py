"""
Paper 5 implementation:
Michael R. Shirts and John D. Chodera,
"Statistically optimal analysis of samples from multiple equilibrium states"
J. Chem. Phys. 129, 124105 (2008).

Connection to the previous repository module
--------------------------------------------
02_umbrella_sampling/umbrella_sampling.py creates several biased equilibrium
windows and saves the raw samples from each window.  This script reads those
samples and applies the MBAR self-consistent equations to combine all windows.

Scientific question
-------------------
Given samples from K different biased equilibrium states, how can we estimate:

1) relative free energies between those states,
2) equilibrium expectations in an unsampled target state,
3) an unbiased probability distribution / PMF,
4) whether neighboring sampled states overlap enough?

Core equation
-------------
For Boltzmann-sampled states, Paper 5 Eq. (11) gives the self-consistent MBAR
equations for the dimensionless free energies f_i:

    f_i = -log sum_n [
        exp(-u_i(x_n))
        /
        sum_k N_k exp(f_k - u_k(x_n))
    ]

Only free-energy differences are meaningful, so this implementation fixes
f_0 = 0 after every iteration.

Uncertainty note
----------------
The paper derives an asymptotic covariance estimator (Eqs. 8-12).  To keep
this educational implementation transparent and memory-efficient for a large
number of samples, this script uses an OPTIONAL stratified bootstrap for PMF
uncertainty instead of constructing the paper's full covariance machinery.
The MBAR point estimator itself follows Eq. (11).

Assumptions
-----------
The MBAR derivation assumes equilibrium samples.  Paper 5 also discusses the
need to account for correlated time-series data.  The previous module stores
strided samples as a simple demonstration; for production molecular dynamics,
estimate statistical inefficiency and subsample appropriately before MBAR.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


# ---------------------------------------------------------------------------
# The physical model and umbrella definition must match Paper 2's module.
# ---------------------------------------------------------------------------

KB = 1.0
T = 1.0
BETA = 1.0 / (KB * T)

BARRIER_SCALE = 5.0

X_MIN = -2.2
X_MAX = 2.2
N_BINS = 180


def physical_potential(x: np.ndarray | float):
    """Unbiased double-well potential U(x) = a (x^2 - 1)^2."""
    return BARRIER_SCALE * (np.asarray(x) ** 2 - 1.0) ** 2


def umbrella_bias(
    x: np.ndarray | float,
    center: float,
    k_bias: float,
):
    """Harmonic umbrella W_i(x) = 1/2 k_i (x - center_i)^2."""
    x = np.asarray(x)
    return 0.5 * k_bias * (x - center) ** 2


def reduced_potential(
    x: np.ndarray,
    center: float,
    k_bias: float,
):
    """
    Dimensionless reduced potential for one sampled state:

        u_i(x) = beta [U(x) + W_i(x)]
    """
    return BETA * (
        physical_potential(x)
        + umbrella_bias(x, center, k_bias)
    )


def target_reduced_potential(x: np.ndarray):
    """
    Dimensionless reduced potential for the unbiased target state:

        u_0(x) = beta U(x)
    """
    return BETA * physical_potential(x)


# ---------------------------------------------------------------------------
# Numerically stable log-sum-exp.
# ---------------------------------------------------------------------------

def logsumexp(values: np.ndarray, axis=None):
    """
    Compute log(sum(exp(values))) stably without requiring SciPy.
    """
    values = np.asarray(values)

    maximum = np.max(
        values,
        axis=axis,
        keepdims=True,
    )

    shifted = np.exp(values - maximum)

    result = maximum + np.log(
        np.sum(
            shifted,
            axis=axis,
            keepdims=True,
        )
    )

    if axis is None:
        return float(np.squeeze(result))

    return np.squeeze(result, axis=axis)


