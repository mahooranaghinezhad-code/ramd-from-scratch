def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            "MBAR analysis of the umbrella-window data generated "
            "by the Paper 2 module."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=Path("results_paper2"),
        help=(
            "Directory containing umbrella_metadata.csv and "
            "window_XX_samples.csv files."
        ),
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results_paper5"),
        help="Directory for MBAR outputs.",
    )

    parser.add_argument(
        "--max-samples-per-window",
        type=int,
        default=0,
        help=(
            "0 = use all saved samples; positive value = evenly "
            "thin each window to at most this many configurations."
        ),
    )

    parser.add_argument(
        "--bootstrap",
        type=int,
        default=0,
        help=(
            "Number of optional stratified-bootstrap replicates "
            "for PMF uncertainty. 0 disables bootstrap."
        ),
    )

    return parser.parse_args()


def main():
    args = parse_arguments()

    run_analysis(
        input_directory=args.input,
        output_directory=args.output,
        max_samples_per_window=args.max_samples_per_window,
        n_bootstrap=args.bootstrap,
    )


if __name__ == "__main__":
    main()
