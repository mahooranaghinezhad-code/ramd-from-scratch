def save_free_energies(
    output_directory: Path,
    windows,
    f_k: np.ndarray,
):
    path = output_directory / "sampled_state_free_energies.csv"

    with open(
        path,
        "w",
        encoding="utf-8",
    ) as handle:
        handle.write(
            "state_index,center,k_bias,N_used,f_relative\n"
        )

        for k, window in enumerate(windows):
            handle.write(
                f"{window['index']},"
                f"{window['center']},"
                f"{window['k_bias']},"
                f"{window['n_used']},"
                f"{f_k[k]}\n"
            )


def save_pmf(
    output_directory: Path,
    centers: np.ndarray,
    probability: np.ndarray,
    reconstructed_pmf: np.ndarray,
    exact: np.ndarray,
    uncertainty: np.ndarray | None,
):
    if uncertainty is None:
        uncertainty = np.full(
            len(centers),
            np.nan,
        )

    matrix = np.column_stack(
        [
            centers,
            probability,
            reconstructed_pmf,
            exact,
            uncertainty,
        ]
    )

    np.savetxt(
        output_directory / "mbar_pmf.csv",
        matrix,
        delimiter=",",
        header=(
            "x,unbiased_probability_mass,"
            "mbar_pmf,exact_pmf,bootstrap_pmf_std"
        ),
        comments="",
    )


def plot_pmf(
    output_directory: Path,
    centers: np.ndarray,
    reconstructed_pmf: np.ndarray,
    exact: np.ndarray,
    uncertainty: np.ndarray | None,
):
    plt.figure(figsize=(9, 6))

    plt.plot(
        centers,
        exact,
        linewidth=3,
        label="Exact PMF",
    )

    plt.plot(
        centers,
        reconstructed_pmf,
        linewidth=2,
        label="MBAR reconstruction",
    )

    if uncertainty is not None:
        valid = (
            np.isfinite(reconstructed_pmf)
            & np.isfinite(uncertainty)
        )

        plt.fill_between(
            centers[valid],
            (
                reconstructed_pmf[valid]
                - uncertainty[valid]
            ),
            (
                reconstructed_pmf[valid]
                + uncertainty[valid]
            ),
            alpha=0.25,
            label="Bootstrap ±1 SD",
        )

    plt.xlabel("Reaction coordinate x")
    plt.ylabel("Free energy / kBT")
    plt.title(
        "Unbiased PMF from multistate MBAR reweighting"
    )

    plt.ylim(0.0, 9.0)
    plt.legend()
    plt.tight_layout()

    plt.savefig(
        output_directory / "mbar_pmf.png",
        dpi=220,
    )

    plt.close()


def plot_overlap(
    output_directory: Path,
    overlap: np.ndarray,
    windows,
):
    labels = [
        f"{window['center']:.2f}"
        for window in windows
    ]

    plt.figure(figsize=(7, 6))

    image = plt.imshow(
        overlap,
        origin="lower",
        vmin=0.0,
        vmax=1.0,
        aspect="equal",
    )

    plt.colorbar(
        image,
        label="Average MBAR responsibility",
    )

    plt.xticks(
        range(len(labels)),
        labels,
        rotation=45,
    )

    plt.yticks(
        range(len(labels)),
        labels,
    )

    plt.xlabel("State receiving responsibility")
    plt.ylabel("State that generated samples")
    plt.title("MBAR state-overlap diagnostic")
    plt.tight_layout()

    plt.savefig(
        output_directory / "mbar_overlap.png",
        dpi=220,
    )

    plt.close()


# ---------------------------------------------------------------------------
# Main scientific workflow.
# ---------------------------------------------------------------------------

def run_analysis(
    input_directory: Path,
    output_directory: Path,
    max_samples_per_window: int,
    n_bootstrap: int,
):
    metadata_path = (
        input_directory
        / "umbrella_metadata.csv"
    )

    metadata = load_metadata(
        metadata_path
    )

    windows = load_window_samples(
        input_directory,
        metadata,
        max_samples_per_window=max_samples_per_window,
    )

    pooled_samples, origin_state = pool_samples(
        windows
    )

    N_k = np.array(
        [
            window["n_used"]
            for window in windows
        ],
        dtype=float,
    )

    print(
        f"Loaded {len(windows)} sampled states "
        f"and {len(pooled_samples)} pooled configurations."
    )

    u_kn = build_reduced_potential_matrix(
        pooled_samples,
        windows,
    )

    print("\nSolving MBAR Eq. (11)...")

    f_k, iterations, final_change = solve_mbar(
        u_kn,
        N_k,
    )

    print(
        f"Converged after {iterations} iterations; "
        f"max delta f = {final_change:.3e}"
    )

    target_u_n = target_reduced_potential(
        pooled_samples
    )

    target_weights, f_target = (
        unsampled_target_weights(
            target_u_n,
            f_k,
            u_kn,
            N_k,
        )
    )

    # Example equilibrium expectations in the unbiased state.
    mean_x = weighted_expectation(
        pooled_samples,
        target_weights,
    )

    mean_x2 = weighted_expectation(
        pooled_samples**2,
        target_weights,
    )

    effective_sample_size = (
        1.0
        / np.sum(
            target_weights**2
        )
    )

    print("\nUnbiased target state")
    print(
        f"  f_target          = {f_target:.6f}"
    )
    print(
        f"  <x>               = {mean_x:.6f}"
    )
    print(
        f"  <x^2>             = {mean_x2:.6f}"
    )
    print(
        f"  weight ESS         = {effective_sample_size:.1f}"
    )

    edges = np.linspace(
        X_MIN,
        X_MAX,
        N_BINS + 1,
    )

    centers = 0.5 * (
        edges[:-1]
        + edges[1:]
    )

    probability = weighted_probability_mass(
        pooled_samples,
        target_weights,
        edges,
    )

    reconstructed_pmf = probability_to_pmf(
        probability
    )

    exact = exact_pmf(
        centers
    )

    error = pmf_rmse(
        reconstructed_pmf,
        exact,
    )

    print(
        f"  PMF RMSE           = {error:.6f}"
    )

    W_nk = sampled_state_weights(
        f_k,
        u_kn,
        N_k,
    )

    overlap = mbar_overlap_matrix(
        W_nk,
        origin_state,
        N_k,
    )

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    uncertainty = None

    if n_bootstrap > 0:
        print(
            f"\nRunning {n_bootstrap} stratified bootstrap replicates..."
        )

        uncertainty = stratified_bootstrap_pmf(
            windows,
            edges,
            n_bootstrap=n_bootstrap,
            seed=2030,
            original_f=f_k,
        )

    save_free_energies(
        output_directory,
        windows,
        f_k,
    )

    save_pmf(
        output_directory,
        centers,
        probability,
        reconstructed_pmf,
        exact,
        uncertainty,
    )

    np.savetxt(
        output_directory / "mbar_overlap.csv",
        overlap,
        delimiter=",",
    )

    with open(
        output_directory / "summary.txt",
        "w",
        encoding="utf-8",
    ) as handle:
        handle.write(
            "Paper 5 MBAR analysis\n"
        )
        handle.write(
            f"sampled states: {len(windows)}\n"
        )
        handle.write(
            f"pooled configurations: {len(pooled_samples)}\n"
        )
        handle.write(
            f"iterations: {iterations}\n"
        )
        handle.write(
            f"final max delta f: {final_change}\n"
        )
        handle.write(
            f"target f: {f_target}\n"
        )
        handle.write(
            f"<x>: {mean_x}\n"
        )
        handle.write(
            f"<x^2>: {mean_x2}\n"
        )
        handle.write(
            f"weight ESS: {effective_sample_size}\n"
        )
        handle.write(
            f"PMF RMSE: {error}\n"
        )

    plot_pmf(
        output_directory,
        centers,
        reconstructed_pmf,
        exact,
        uncertainty,
    )

    plot_overlap(
        output_directory,
        overlap,
        windows,
    )

